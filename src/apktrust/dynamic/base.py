from abc import ABC, abstractmethod
from .models import DynamicProviderStatus, DynamicRequest, DynamicJob, DynamicResult
class DynamicProvider(ABC):
    @abstractmethod
    async def health_check(self) -> DynamicProviderStatus: ...
    @abstractmethod
    async def discover_devices(self) -> list[dict]: ...
    async def prepare(self,request: DynamicRequest) -> dict:
        return {}
    @abstractmethod
    async def submit(self, request: DynamicRequest) -> DynamicJob: ...
    @abstractmethod
    async def get_status(self, job: DynamicJob) -> DynamicJob: ...
    @abstractmethod
    async def collect_results(self, job: DynamicJob) -> DynamicResult: ...
    @abstractmethod
    async def cancel(self, job: DynamicJob) -> DynamicJob: ...
    @abstractmethod
    async def read_artifact(self, artifact, offset=0, limit=65536) -> bytes: ...
